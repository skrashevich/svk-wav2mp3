func TestConvert_OutputPathAutoGenerated(t *testing.T) {
	wavPath := generateSineWAV(t, 44100, 2, 16, 0.5)
	defer os.Remove(wavPath)

	// Manually strip WAV extension for predictable name
	expectedMP3 := wavPath[:len(wavPath)-4] + ".mp3"
	defer os.Remove(expectedMP3)

	opts := config.DefaultConvertOptions()
	opts.InputPath = wavPath
	opts.OutputPath = "" // auto
	opts.Quiet = true

	stats, err := Convert(context.Background(), opts)
	if err != nil {
		t.Fatalf("conversion failed: %v", err)
	}
	if stats.OutputPath != expectedMP3 {
		t.Errorf("expected path %s, got %s", expectedMP3, stats.OutputPath)
	}
}

func TestConvert_Stereo24bit(t *testing.T) {
	const fixture = "../../testdata/fixtures/sine_44100_stereo_24.wav"
	if _, err := os.Stat(fixture); os.IsNotExist(err) {
		t.Skip("fixture missing, run: go run testdata/gen_fixtures.go")
	}

	outPath := t.TempDir() + "/out_24bit.mp3"

	opts := config.DefaultConvertOptions()
	opts.InputPath = fixture
	opts.OutputPath = outPath
	opts.Quiet = true

	stats, err := Convert(context.Background(), opts)
	if err != nil {
		t.Fatalf("conversion 24-bit failed: %v", err)
	}
	if stats.WAVInfo.BitDepth != 24 {
		t.Errorf("expected BitDepth=24, got %d", stats.WAVInfo.BitDepth)
	}
	if stats.OutputSizeB == 0 {
		t.Error("output file is empty")
	}
}

func TestConvert_CancelContext(t *testing.T) {
	wavPath := generateSineWAV(t, 44100, 2, 16, 0.5)
	defer os.Remove(wavPath)

	outPath := wavPath[:len(wavPath)-4] + ".mp3"
	defer os.Remove(outPath)

	ctx, cancel := context.WithCancel(context.Background())
	cancel() // immediate cancelation

	opts := config.DefaultConvertOptions()
	opts.InputPath = wavPath
	opts.OutputPath = outPath
	opts.Quiet = true

	_, err := Convert(ctx, opts)
	if err == nil {
		t.Error("expected error on cancelled context")
	}

	// Partial file should be removed
	if _, statErr := os.Stat(outPath); !os.IsNotExist(statErr) {
		t.Error("partial output file should be removed on cancelation")
	}
}
